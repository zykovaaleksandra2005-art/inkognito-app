func (a *App) startup(ctx context.Context) {
	a.ctx = ctx
}

func (a *App) GetFeedQuotes() []BookQuote {
	a.mu.Lock()
	defer a.mu.Unlock()
	return a.cards
}

func (a *App) ToggleLike(id int) bool {
	a.mu.Lock()
	defer a.mu.Unlock()
	for i, card := range a.cards {
		if card.ID == id {
			a.cards[i].IsLiked = !a.cards[i].IsLiked
			return a.cards[i].IsLiked
		}
	}
	return false
}
